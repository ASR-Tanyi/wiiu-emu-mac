#!/usr/bin/env python3
"""Generate the OSScreen font (Phase 6.8) from DejaVu Sans Mono.

OSScreenPutFontEx draws text "with a built-in monospace font, coloured white,
and anti-aliased" (wut's documentation). The console's own font is system
data and is not shipped; this renders an open one into the same shape instead:
one 12x24 cell per printable ASCII character, 4 bits of coverage per pixel.

    scripts/gen_screen_font.py [path/to/DejaVuSansMono.ttf] > src/hle/src/screen_font.inc

Needs Pillow. The output is checked in, so this only runs when the font is
being changed -- and it is deterministic, so running it again is a no-op.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

CELL_WIDTH = 12
CELL_HEIGHT = 24
FIRST = 0x20
LAST = 0x7E

DEFAULT_FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"


def pick_size(path):
    """The largest size whose advance fits the cell and whose line fits too."""
    best = None
    for size in range(8, 40):
        font = ImageFont.truetype(path, size)
        ascent, descent = font.getmetrics()
        if font.getlength("M") <= CELL_WIDTH and ascent + descent <= CELL_HEIGHT:
            best = size
    return best


def render(path):
    size = pick_size(path)
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    top = (CELL_HEIGHT - (ascent + descent)) // 2

    glyphs = []
    for code in range(FIRST, LAST + 1):
        image = Image.new("L", (CELL_WIDTH, CELL_HEIGHT), 0)
        draw = ImageDraw.Draw(image)
        advance = font.getlength(chr(code))
        left = (CELL_WIDTH - advance) / 2
        draw.text((left, top), chr(code), fill=255, font=font)
        # 4 bits of coverage: enough for an edge to look smooth, half the size.
        glyphs.append([(value * 15 + 127) // 255 for value in image.tobytes()])
    return size, glyphs


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FONT
    size, glyphs = render(path)

    out = sys.stdout
    out.write("// Generated by scripts/gen_screen_font.py -- do not edit by hand.\n")
    out.write("//\n")
    out.write(f"// DejaVu Sans Mono at {size}px, one {CELL_WIDTH}x{CELL_HEIGHT} cell per\n")
    out.write(f"// character from {FIRST:#04x} to {LAST:#04x}, row-major, two pixels per byte\n")
    out.write("// (high nibble first), each a 4-bit coverage value.\n")
    out.write("//\n")
    out.write("// Bitmaps rendered from DejaVu Sans Mono. DejaVu fonts are a derivative of\n")
    out.write("// Bitstream Vera: Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.\n")
    out.write("// Bitstream Vera is a trademark of Bitstream, Inc. DejaVu changes are in the\n")
    out.write("// public domain. Permission is hereby granted, free of charge, to any person\n")
    out.write("// obtaining a copy of the fonts accompanying this license (\"Fonts\") and\n")
    out.write("// associated documentation files, to reproduce and distribute the Font\n")
    out.write("// Software, including without limitation the rights to use, copy, merge,\n")
    out.write("// publish, distribute, and/or sell copies of the Font Software, subject to\n")
    out.write("// the condition that the above copyright and trademark notices and this\n")
    out.write("// permission notice are included in all copies of the Font Software.\n")
    out.write("\n")
    out.write(f"inline constexpr u32 kFontCellWidth = {CELL_WIDTH};\n")
    out.write(f"inline constexpr u32 kFontCellHeight = {CELL_HEIGHT};\n")
    out.write(f"inline constexpr u32 kFontFirst = {FIRST:#04x};\n")
    out.write(f"inline constexpr u32 kFontLast = {LAST:#04x};\n")
    per_glyph = CELL_WIDTH * CELL_HEIGHT // 2
    out.write(f"inline constexpr u32 kFontGlyphBytes = {per_glyph};\n\n")
    out.write(f"inline constexpr std::array<u8, {per_glyph * len(glyphs)}> kFont{{{{\n")
    for index, glyph in enumerate(glyphs):
        packed = [(glyph[i] << 4) | glyph[i + 1] for i in range(0, len(glyph), 2)]
        out.write(f"    // {FIRST + index:#04x} {chr(FIRST + index)!r}\n")
        for row in range(0, len(packed), 12):
            chunk = ", ".join(f"0x{value:02X}" for value in packed[row:row + 12])
            out.write(f"    {chunk},\n")
    out.write("}};\n")


if __name__ == "__main__":
    main()
